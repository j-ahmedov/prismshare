def write_clip_check_frames(params: CodecParams, out_dir: Path) -> Path:
    """One deterministic frame of ``params`` for clip-checking (written once, reused by every run)."""
    folder = out_dir / f"c{params.colour_depth}_px{params.cell_px}"
    if (folder / "frames.json").exists():
        return folder
    from prism_share.codec.framing import frame_capacity

    payload = keystream(params.seed, _CLIP_PAYLOAD_DOMAIN, frame_capacity(params).block_bytes)
    frames = encode_frames(payload, params, n_frames=1)
    paths = save_frames([f.image for f in frames], folder)
    doc = {
        "purpose": "clip check only - never a measurement",
        "params": params.to_dict(),
        "params_label": params.label,
        "params_fingerprint": params.fingerprint(),
        "payload": {"length": len(payload), "keystream": {"seed": params.seed, "domain": _CLIP_PAYLOAD_DOMAIN,
                                                          "bytes": len(payload)}},
        "frames": [{"file": p.name, "block_id": f.header.block_id, "frame_index": f.frame_index,
                    "image_sha256": image_sha256(f.image)} for p, f in zip(paths, frames, strict=True)],
    }
    (folder / "frames.json").write_text(json.dumps(doc, indent=1) + "\n")
    return folder


def new_run_definition(run_id: str, frames: Path, block_id: int, condition: dict[str, Any], *,
                       runs_dir: Path = DEFAULT_RUNS_DIR, clip_dir: Path = DEFAULT_CLIP_CHECK_DIR,
                       overwrite: bool = False) -> Path:
    """Write experiments/runs/<run_id>.yaml with its clip-check pair, and the clip-check frames."""
    from prism_share.transmit.reference import extreme_configurations

    path = run_definition_path(run_id, runs_dir)
    if path.exists() and not overwrite:
        raise FileExistsError(f"{path} exists; run ids are join keys and are never silently reused")
    root = _root(runs_dir)
    meta = json.loads((_resolve(frames, root) / "frames.json").read_text(encoding="utf-8"))
    if block_id not in {int(f["block_id"]) for f in meta["frames"]}:
        raise ValueError(f"block_id {block_id} is not in {frames}/frames.json")
    frame_px = int(meta["params"]["frame_px"])
    clip = {}
    for role, row in zip(CLIP_CHECK_ROLES, extreme_configurations(), strict=True):
        params = CodecParams(colour_depth=row.colour_depth, cell_px=row.cell_px, frame_px=frame_px)
        folder = write_clip_check_frames(params, _resolve(clip_dir, root))
        clip[role] = {"colour_depth": row.colour_depth, "cell_px": row.cell_px, "frames": _relative(folder, root),
                      "frame_mean_linear": round(row.frame_mean, _LUMINANCE_DECIMALS),
                      "stops_vs_reference": round(row.stops_vs_reference, _STOPS_DECIMALS)}
    doc = {"run_id": run_id, "frames": str(frames), "displayed": [block_id], "condition": condition, "clip_check": clip}
    runs_dir.mkdir(parents=True, exist_ok=True)
    path.write_text(yaml.safe_dump(doc, sort_keys=False))
    return path


def _relative(path: Path, root: Path) -> str:
    try:
        return str(path.resolve().relative_to(root))
    except ValueError:
        return str(path)


def _scalar(text: str) -> str | int | float | bool:
    value = yaml.safe_load(text)
    return value if isinstance(value, str | int | float | bool) else text


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Laptop-side run definitions.")
    sub = parser.add_subparsers(dest="command", required=True)
    n = sub.add_parser("new", help="write a run definition with its clip-check pair")
    n.add_argument("--run-id", required=True)
    n.add_argument("--frames", required=True, help="folder written by `display frames`")
    n.add_argument("--block", type=int, required=True, help="the one block_id this run holds on screen")
    n.add_argument("--condition", action="append", default=[], metavar="NAME=VALUE")
    n.add_argument("--runs-dir", default=str(DEFAULT_RUNS_DIR))
    n.add_argument("--clip-dir", default=str(DEFAULT_CLIP_CHECK_DIR))
    n.add_argument("--overwrite", action="store_true")
    args = parser.parse_args(argv)
    condition = {}
    for item in args.condition:
        name, _, value = item.partition("=")
        condition[name] = _scalar(value)
    path = new_run_definition(args.run_id, Path(args.frames), args.block, condition, runs_dir=Path(args.runs_dir),
                              clip_dir=Path(args.clip_dir), overwrite=args.overwrite)
    doc = yaml.safe_load(path.read_text())
    print(f"wrote {path}")
    for role in CLIP_CHECK_ROLES:
        c = doc["clip_check"][role]
        print(f"  clip-check {role}: {c['colour_depth']} colours, {c['cell_px']} px ({c['stops_vs_reference']:+.3f} stops) -> {c['frames']}")
    print(f"  display with: python -m prism_share.transmit.display measure {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
